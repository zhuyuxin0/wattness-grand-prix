// Bundles the Wattness evaluator and the sealed 2026-11-26 record into
// vendor/wattness-evaluator.js, inside this deploy codeLocation.
//
// The managed platform ships one esbuild bundle of src/unifiedMain.ts and
// nothing else from disk, so the evaluator and its fixture have to be
// importable modules here, not files read at run time. Run from the
// repository after `pnpm install` and building @gatelock/core and
// @gatelock/verifier.
import { mkdirSync, statSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const agentDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const adapterDir = resolve(agentDir, "../../..");
const outfile = resolve(agentDir, "vendor/wattness-evaluator.js");

const adapter = await import(resolve(adapterDir, "dist/index.js")).catch(() => {
  throw new Error(`build the adapter first: pnpm --filter @gatelock/adapter-agent-studio build (looked in ${adapterDir}/dist)`);
});
const files = await adapter.fixtureFiles(adapter.DEFAULT_FIXTURE, adapter.RESOURCES);
const index = files["manifest.json"];
const receipt = files["record.bsc-testnet.json"];
if (receipt.chainId !== 97 || receipt.root !== index.root) throw new Error("fixture receipt does not match the testnet fleet root");

const record = {
  operatingDay: index.operating_day,
  root: index.root,
  leafCount: index.leaf_count,
  codeTree: index.code_tree,
  chainId: receipt.chainId,
  contract: receipt.contract,
  key: receipt.key,
  txHash: receipt.txHash,
  blockNumber: receipt.blockNumber,
};

const entry = `
import { evaluate, parseRequest, reportDigest, RESOURCES } from ${JSON.stringify(resolve(adapterDir, "src/index.ts"))};
const FIXTURE = ${JSON.stringify(files)};
export const RECORD = Object.freeze(${JSON.stringify(record)});
export function evaluateSealedRecord(request, options = {}) {
  return evaluate(request, { now: options.now, fixture: FIXTURE });
}
export { parseRequest, reportDigest, RESOURCES };
`;

mkdirSync(dirname(outfile), { recursive: true });
await build({
  stdin: { contents: entry, resolveDir: adapterDir, sourcefile: "wattness-evaluator-entry.js", loader: "js" },
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  outfile,
  legalComments: "inline",
  logLevel: "warning",
  banner: { js: "// Generated by scripts/vendor-evaluator.mjs from packages/adapters/agent-studio. Do not edit." },
});
const kib = Math.round(statSync(outfile).size / 1024);
process.stdout.write(`vendored ${relative(agentDir, outfile)} (${kib} KiB): ${record.operatingDay} root ${record.root}, ${adapter.RESOURCES.join(", ")}\n`);
